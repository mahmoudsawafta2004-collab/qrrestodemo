function getLang() {
  return localStorage.getItem('qrresto_lang') || Store.get().settings.lang || 'ar';
}
function setLang(lang) {
  localStorage.setItem('qrresto_lang', lang);
}
function t(key) {
  const lang = getLang();
  return (I18N[lang] && I18N[lang][key]) || key;
}
function tField(field) {
  const lang = getLang();
  if (!field) return '';
  return field[lang] || field.ar || field.en || '';
}
function applyDocDir() {
  const lang = getLang();
  document.documentElement.lang = lang;
  document.documentElement.dir = I18N[lang].dir;
}
